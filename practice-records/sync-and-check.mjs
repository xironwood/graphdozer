import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'astro';
import { decodeHTML } from 'entities';
import { parse, TEXT_NODE } from 'ultrahtml';
import { querySelector } from 'ultrahtml/selector';

const root = fileURLToPath(new URL('../', import.meta.url));
const records = join(root, 'practice-records/practices/graphdozer-sandbox');
const src = join(root, 'src');
const factsFile = join(src, 'data/website-facts.generated.json');
const insuranceFile = join(src, 'data/insurance.generated.json');
const llmsFile = join(root, 'public/llms.txt');
const read = (file) => readFileSync(file, 'utf8');

function filesIn(dir) {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => join(entry.parentPath, entry.name)).sort();
}

function writeGenerated(file, content) {
  if (existsSync(file) && read(file) === content) return;
  mkdirSync(dirname(file), { recursive: true });
  const temporary = file + '.' + process.pid + '.tmp';
  writeFileSync(temporary, content);
  renameSync(temporary, file);
}

function checkRecords(facts, insurance) {
  assert.equal(facts.isSandboxTestSite, true, 'The practice record must identify this sandbox.');
  const { clinician, location, hours, waitlist, pricing } = facts;
  assert.ok(Array.isArray(location.telehealthStates) && location.telehealthStates.length, 'Missing telehealth boundary.');
  assert.ok(Array.isArray(insurance.carriers), 'Missing carrier list.');
  const textFields = [facts.practiceName, facts.crisisDisclaimer, facts.domain, clinician.name,
    clinician.licenseNumber, clinician.licenseState, clinician.boardLookupUrl, location.city,
    location.state, ...location.telehealthStates, hours.display, hours.schemaHours, waitlist.ctaLabel,
    waitlist.contactPageTitle, insurance.couplesPolicy, ...insurance.carriers.flatMap((c) => [c.name, c.shortLabel])];
  assert.ok(textFields.every((s) => typeof s === 'string' && s.trim()), 'Missing text in approved records.');
  assert.equal(typeof waitlist.acceptingNewClients, 'boolean', 'Invalid availability.');
  for (const key of ['intake', 'individual', 'couples', 'lateCancellationFee', 'consultationMinutes', 'consultationFee']) {
    assert.ok(Number.isFinite(pricing[key]) && pricing[key] >= 0, 'Invalid pricing.' + key);
  }
}

function summary(facts, insurance, carrierList) {
  const { clinician, location, pricing, waitlist } = facts;
  return [
    '# ' + facts.practiceName,
    '',
    '> Educational demonstration of a solo counseling practice in ' + location.city + ', ' + location.state + '.',
    '',
    `${clinician.name} holds ${clinician.licenseState} test license ${clinician.licenseNumber} in this sandbox.`,
    'Office hours are ' + facts.hours.display + '.',
    'Telehealth is limited to clients physically located in ' + location.telehealthStates.join(', ') + ' during a session.',
    waitlist.acceptingNewClients ? 'The sandbox is accepting new clients.' : 'The sandbox is waitlisting new clients. Intake appointments are closed.',
    `[Practice overview](${facts.domain}/)`,
    '',
    '## Fees and insurance',
    '',
    '| Service | Fee |',
    '| --- | ---: |',
    `| Intake | $${pricing.intake} |`,
    `| Individual session | $${pricing.individual} |`,
    `| Couples session | $${pricing.couples} |`,
    `| Late cancellation | $${pricing.lateCancellationFee} |`,
    `| ${pricing.consultationMinutes}-minute consultation | $${pricing.consultationFee} |`,
    '',
    carrierList ? 'Listed carriers for individual therapy include ' + carrierList + '.' : 'The sandbox lists no carriers for individual therapy.',
    insurance.couplesPolicy,
    '',
    facts.crisisDisclaimer,
    '',
  ].join('\n');
}

// A checksum lets us distinguish a stale generated summary from a hand edit even
// when the source records, generator template or generated JSON change together.
const marker = '\n<!-- Generated by npm run sync. SHA-256 ';
function stampedSummary(body) {
  return body + marker + createHash('sha256').update(body).digest('hex') + ' -->\n';
}

function checkExistingSummary(facts, insurance, carrierList) {
  if (!existsSync(llmsFile)) return;
  const previous = read(llmsFile);
  const end = previous.lastIndexOf(marker);
  if (end >= 0 && previous === stampedSummary(previous.slice(0, end))) return;
  checkCopy('public/llms.txt', previous, facts.hours);
  checkCarrierLiterals('public/llms.txt', previous.replace(carrierList, ''), insurance);
  throw new Error('public/llms.txt has manual changes. Restore the generated file and edit the approved records.');
}

const day = '(?:Monday|Mon?|M|Tuesday|Tues?|Tu|T|Wednesday|Wed?|W|Thursday|Thu(?:rs?)?|Th|Friday|Fri?|F|Saturday|Sat?|Sunday|Sun?)';
const range = '(?:[-–—−]|to|through|thru|until)';
const schedulePatterns = [
  /\b\d{1,2}:[0-5]\d\b/,
  /\b\d{1,2}\s*[ap]\.?m\.?(?!\w)/i,
  /\b\d{1,2}[ap]\b/i,
  new RegExp('\\b' + day + '\\.?\\s*' + range + '\\s*' + day + '\\b', 'i'),
  new RegExp('\\b(?:open|closed)\\s+(?:on\\s+)?(?:weekdays?|weekends?|' + day + 's?)\\b', 'i'),
  new RegExp('\\b(?:hours|open|weekdays?|weekends?|' + day + ')\\b[^\\n<>]{0,30}?\\b\\d{1,2}\\s*' + range + '\\s*\\d{1,2}\\b', 'i'),
  /(?:^|[>"'`])\s*\d{1,2}\s*(?:[-–—−]|to)\s*\d{1,2}\s*(?=$|[<"'`])/im,
  /\b(?:noon|midnight|24\s*\/\s*7|open\s+24\s+hours)\b/i,
];

function checkProhibitedTerms(label, text) {
  for (const [rule, pattern] of [
    ['curative claim', /\bcure(?:s|d)?\b/i],
    ['tracking script', /fbevents\.js|tiktok\.com|gtag\/js|googletagmanager\.com/i],
  ]) {
    const match = text.match(pattern);
    if (match) throw new Error(`${label}: ${rule} "${match[0]}".`);
  }
}

function checkCopy(label, text, hours) {
  checkProhibitedTerms(label, text);
  // Only the approved display and Schema.org schedules may appear as literals.
  const other = text.replaceAll(hours.display, '').replaceAll(hours.schemaHours, '');
  for (const pattern of schedulePatterns) {
    const match = other.match(pattern);
    if (match) throw new Error(`${label}: unapproved hours near "${match[0]}". Use practice.hours.`);
  }
}

function checkCarrierLiterals(label, text, insurance) {
  const plain = text.replace(/<[^>\n]+>/g, '');
  const content = (text + '\n' + plain).replace(/(?:\s|&nbsp;)+/gi, ' ').toLowerCase();
  for (const { name, shortLabel } of insurance.carriers) {
    for (const term of new Set([name, shortLabel])) {
      if (content.includes(term.toLowerCase())) {
        throw new Error(`${label}: hardcoded carrier "${term}". Read insurance.generated.json.`);
      }
    }
  }
}

function checkSource(file, source, facts, insurance) {
  const label = relative(root, file);
  const text = decodeHTML(source);
  checkCopy(label, text, facts.hours);
  if (file !== insuranceFile) checkCarrierLiterals(label, text, insurance);
}

const blocks = new Set('address article aside blockquote br dd div dl dt footer h1 h2 h3 h4 h5 h6 header hr li main nav ol p section table td th tr ul'.split(' '));
function visibleText(node) {
  if (!node) return '';
  if (node.type === TEXT_NODE) return decodeHTML(node.value);
  if (['head', 'script', 'style', 'template', 'noscript'].includes(node.name) ||
      node.attributes?.hidden !== undefined || node.attributes?.['aria-hidden'] === 'true') return '';
  const text = (node.children ?? []).map(visibleText).join('');
  return blocks.has(node.name) ? ' ' + text + ' ' : text;
}

async function checkPages(facts) {
  const scratch = join(root, '.astro');
  mkdirSync(scratch, { recursive: true });
  const output = mkdtempSync(join(scratch, 'compliance-'));
  try {
    await build({ root, outDir: output, logLevel: 'error' });
    const files = filesIn(output);
    for (const file of files.filter((path) => /\.m?js$/i.test(path))) {
      checkProhibitedTerms(relative(output, file), read(file));
    }
    const pages = files.filter((file) => file.endsWith('.html'));
    assert.ok(pages.length, 'Astro emitted no HTML pages.');
    for (const file of pages) {
      const route = relative(output, file);
      const html = read(file);
      const body = visibleText(querySelector(parse(html), 'body')).replace(/\s+/g, ' ');
      checkCopy(route, html, facts.hours);
      checkCopy(route, body, facts.hours);
      for (const resource of ['988', '741741']) {
        assert.ok(new RegExp('\\b' + resource + '\\b').test(body), `${route}: missing visible crisis resource ${resource}.`);
      }
      for (const term of [facts.clinician.name.split(',')[0], facts.clinician.licenseNumber]) {
        const exactTerm = new RegExp('(?<![\\p{L}\\p{N}_-])' + RegExp.escape(term) + '(?![\\p{L}\\p{N}_-])', 'u');
        assert.ok(exactTerm.test(body), `${route}: missing visible clinician attribution "${term}".`);
      }
    }
    return pages.length;
  } finally {
    rmSync(output, { recursive: true, force: true });
  }
}

async function sync() {
  const factsText = read(join(records, 'website-facts.json'));
  const insuranceText = read(join(records, 'insurance.json'));
  const facts = JSON.parse(factsText);
  const insurance = JSON.parse(insuranceText);
  checkRecords(facts, insurance);
  const carrierList = insurance.carriers.map(({ name, shortLabel }) =>
    name === shortLabel ? name : `${name} (${shortLabel})`).join(', ');
  checkExistingSummary(facts, insurance, carrierList);
  const machineSummary = summary(facts, insurance, carrierList);
  checkCopy('public/llms.txt', machineSummary, facts.hours);
  // The generated listing is the sole place carrier literals belong in llms.txt.
  checkCarrierLiterals('public/llms.txt', machineSummary.replace(carrierList, ''), insurance);
  checkSource(factsFile, factsText, facts, insurance);
  checkSource(insuranceFile, insuranceText, facts, insurance);
  for (const file of filesIn(src)) {
    if (file !== factsFile && file !== insuranceFile) checkSource(file, read(file), facts, insurance);
  }
  writeGenerated(factsFile, factsText);
  writeGenerated(insuranceFile, insuranceText);
  writeGenerated(llmsFile, stampedSummary(machineSummary));
  const count = await checkPages(facts);
  console.log(`Approved records synced. Compliance passed on ${count} rendered pages and public/llms.txt.`);
}

try {
  await sync();
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
